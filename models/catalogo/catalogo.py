class Catalogo:
    def __init__(self, tipo_produto, nome_flor, preco):
        self.tipo_produto = tipo_produto
        self.nome_flor = nome_flor
        self.preco = preco

def __str__(self):
        return (
            f"Tipo de Produto: {self.tipo_produto} | "
            f"Nome: {self.nome_flor} | "
            f"Preço: R$ {self.preco:.2f}"
        )

